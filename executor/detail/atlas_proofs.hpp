// PlanSearch (RatioSort / OptimalTree / MonotoneCut): order independent tasks
// by descending `benefit / cost` ratio.
struct PlanChoice {
  size_t id{0};
  uint64_t benefit{0};
  uint64_t cost{1};
};

[[nodiscard]] inline std::vector<size_t> OrderPlansByBenefitCostRatio(
    std::span<const PlanChoice> choices) {
  std::vector<PlanChoice> sorted(choices.begin(), choices.end());
  std::stable_sort(sorted.begin(), sorted.end(),
                   [](const PlanChoice& a, const PlanChoice& b) {
                     return a.benefit * b.cost > b.benefit * a.cost;
                   });
  std::vector<size_t> ids;
  ids.reserve(sorted.size());
  for (const auto& c : sorted) {
    ids.push_back(c.id);
  }
  return ids;
}

// OrderedMeasures / RangePlans / EncodedPages / JoinPlans:
// prefix-sum seam energy and Pareto skyline filter over 2D `(cost, latency)`.
[[nodiscard]] inline std::vector<std::pair<int64_t, int64_t>>
Extract2DParetoSkyline(std::span<const std::pair<int64_t, int64_t>> pts) {
  std::vector<std::pair<int64_t, int64_t>> sorted(pts.begin(), pts.end());
  std::sort(sorted.begin(), sorted.end());
  std::vector<std::pair<int64_t, int64_t>> skyline;
  for (const auto& p : sorted) {
    if (skyline.empty() || p.second < skyline.back().second) {
      skyline.push_back(p);
    }
  }
  return skyline;
}

