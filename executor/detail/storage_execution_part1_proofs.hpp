// BagKernels: run-length multiplicity folding `sum(val * mult)`.
[[nodiscard]] inline int64_t FoldMultiplicityRunSum(
    std::span<const std::pair<int64_t, uint64_t>> val_mult_runs) noexcept {
  int64_t acc = 0;
  for (const auto& [v, m] : val_mult_runs) {
    acc += v * static_cast<int64_t>(m);
  }
  return acc;
}

// ClusterOrder (GrayPair): Gray-code encode/decode for locality-preserving
// 2D clustering order.
[[nodiscard]] constexpr uint64_t GrayEncode64(uint64_t x) noexcept {
  return x ^ (x >> 1U);
}

[[nodiscard]] constexpr uint64_t GrayDecode64(uint64_t g) noexcept {
  uint64_t x = g;
  x ^= x >> 1U;
  x ^= x >> 2U;
  x ^= x >> 4U;
  x ^= x >> 8U;
  x ^= x >> 16U;
  x ^= x >> 32U;
  return x;
}

// DerivedZones: monotone floor-division zone-map transfer `[min/d, max/d]`.
[[nodiscard]] constexpr std::pair<uint64_t, uint64_t> FloorDivZoneBounds(
    uint64_t lo, uint64_t hi, uint64_t divisor) noexcept {
  return divisor == 0
             ? std::pair<uint64_t, uint64_t>{0, 0}
             : std::pair<uint64_t, uint64_t>{lo / divisor, hi / divisor};
}

