// RedoPatches: fuse two consecutive affine updates `x -> a*x + b`.
struct AffinePatch {
  int64_t mul{1};
  int64_t add{0};

  [[nodiscard]] constexpr int64_t Apply(int64_t x) const noexcept {
    return (mul * x) + add;
  }
};

[[nodiscard]] constexpr AffinePatch FuseAffinePatches(
    AffinePatch first, AffinePatch second) noexcept {
  return {.mul = second.mul * first.mul,
          .add = (second.mul * first.add) + second.add};
}

// ReferenceEdits / ScopeLookup: resolve innermost non-empty scope binding.
[[nodiscard]] inline std::optional<uint64_t> ResolveInnermostScopeId(
    std::span<const std::optional<uint64_t>> scope_stack) noexcept {
  for (size_t i = scope_stack.size(); i-- > 0;) {
    if (scope_stack[i].has_value()) {
      return scope_stack[i];
    }
  }
  return std::nullopt;
}

// SeekIntervals: exact half-open distance-band seek range `[center - d, center
// + d]` clipped to `[lower_bound, upper_bound]`.
[[nodiscard]] constexpr std::pair<int64_t, int64_t> ClippedDistanceBandSeek(
    int64_t center, int64_t dist, int64_t lower_bound,
    int64_t upper_bound) noexcept {
  const int64_t lo = std::max(lower_bound, center - dist);
  const int64_t hi = std::min(upper_bound, center + dist);
  return lo <= hi ? std::pair<int64_t, int64_t>{lo, hi}
                  : std::pair<int64_t, int64_t>{1, 0};
}

