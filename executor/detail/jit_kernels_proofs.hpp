// Branchless fused range filter + int64 sum over dense columnar lanes.
[[nodiscard]] inline int64_t FusedRangeFilterSumInt64(
    std::span<const int64_t> keys, std::span<const int64_t> payloads,
    int64_t lo, int64_t hi) noexcept {
  const size_t n =
      keys.size() < payloads.size() ? keys.size() : payloads.size();
  int64_t acc = 0;
  for (size_t i = 0; i < n; ++i) {
    const int64_t keep = (keys[i] >= lo && keys[i] <= hi) ? 1 : 0;
    acc += payloads[i] * keep;
  }
  return acc;
}

// Compact selection vector extraction from boolean byte mask.
[[nodiscard]] inline std::vector<uint32_t> CompactMaskToSelectionVector(
    std::span<const uint8_t> mask) {
  std::vector<uint32_t> sel;
  sel.reserve(mask.size());
  for (uint32_t i = 0; i < mask.size(); ++i) {
    if (mask[i] != 0) {
      sel.push_back(i);
    }
  }
  return sel;
}

