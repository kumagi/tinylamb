// ArrayOffsets: slice `[offsets[i], offsets[i + 1])` cardinality & bounds.
[[nodiscard]] constexpr size_t ArraySliceLength(
    std::span<const uint32_t> offsets, size_t idx) noexcept {
  if (idx + 1 >= offsets.size()) {
    return 0;
  }
  return offsets[idx + 1] >= offsets[idx] ? (offsets[idx + 1] - offsets[idx])
                                          : 0;
}

// CalendarRanges: half-open civil-year day interval `[start, end)` containment.
[[nodiscard]] constexpr bool DayInHalfOpenCalendarRange(
    int64_t day, int64_t range_start, int64_t range_end) noexcept {
  return range_start <= day && day < range_end;
}

// FrameRetractions: invertible XOR-parity sliding window retraction.
[[nodiscard]] constexpr uint64_t RetractXorParity(uint64_t acc,
                                                  uint64_t leaving,
                                                  uint64_t entering) noexcept {
  return acc ^ leaving ^ entering;
}

// LexicalCuts: depth-1 comma split positions ignoring nested brackets.
[[nodiscard]] inline std::vector<size_t> FindDepthOneCommaPositions(
    std::string_view text) {
  std::vector<size_t> pos;
  int depth = 0;
  for (size_t i = 0; i < text.size(); ++i) {
    if (text[i] == '[' || text[i] == '(') {
      ++depth;
    } else if (text[i] == ']' || text[i] == ')') {
      --depth;
    } else if (text[i] == ',' && depth == 1) {
      pos.push_back(i);
    }
  }
  return pos;
}

// RecursivePaths: delta-only BFS frontier step deduplicating visited nodes.
[[nodiscard]] inline std::vector<uint64_t> StepDeltaRecursiveFrontier(
    std::span<const uint64_t> next_candidates,
    std::unordered_set<uint64_t>* visited) {
  std::vector<uint64_t> delta;
  for (const uint64_t node : next_candidates) {
    if (visited->insert(node).second) {
      delta.push_back(node);
    }
  }
  return delta;
}

