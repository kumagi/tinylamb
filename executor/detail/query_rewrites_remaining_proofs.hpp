// AnalyticalJoins / DictionaryFiltersAndRanking / FileRangesAndExtrema /
// KeyRoutedJoinStates / PartitionedAggregateStates / RevenueAndShipments /
// SalesAndReturns / ColumnCodecs:
// key-routed join state merge and partitioned aggregate state fold.
[[nodiscard]] inline std::unordered_map<uint64_t, int64_t>
MergePartitionedAggregateStates(
    std::span<const std::unordered_map<uint64_t, int64_t>> shards) {
  std::unordered_map<uint64_t, int64_t> merged;
  for (const auto& shard : shards) {
    for (const auto& [k, v] : shard) {
      merged[k] += v;
    }
  }
  return merged;
}

// ColumnCodecs: run-end binary search lookup returning the value of the run
// covering logical ordinal `row_idx`.
struct RunEndEntry {
  size_t end_excl{0};
  int64_t value{0};
};

[[nodiscard]] inline std::optional<int64_t> LookupRunEndOrdinal(
    std::span<const RunEndEntry> runs, size_t row_idx) noexcept {
  const auto it = std::upper_bound(
      runs.begin(), runs.end(), row_idx,
      [](size_t idx, const RunEndEntry& r) { return idx < r.end_excl; });
  if (it == runs.end()) {
    return std::nullopt;
  }
  return it->value;
}

