// RankedMasks: exact prefix popcount up to bit position `pos` (exclusive).
[[nodiscard]] constexpr size_t PrefixMaskPopcount(uint64_t mask,
                                                  unsigned pos) noexcept {
  if (pos >= 64U) {
    return static_cast<size_t>(std::popcount(mask));
  }
  const uint64_t prefix = (uint64_t{1} << pos) - 1U;
  return static_cast<size_t>(std::popcount(mask & prefix));
}

// OrderedFooters: index-weighted sum over contiguous ordinal range `[lo, hi)`.
[[nodiscard]] constexpr uint64_t ContiguousOrdinalSum(uint64_t lo,
                                                      uint64_t hi) noexcept {
  if (lo >= hi) {
    return 0;
  }
  const uint64_t n = hi - lo;
  return n * (lo + hi - 1) / 2U;
}

// PostingJoins: annulus posting predicate `r_min <= |a - b| <= r_max`.
[[nodiscard]] constexpr bool PostingPairInAnnulus(uint64_t a, uint64_t b,
                                                  uint64_t r_min,
                                                  uint64_t r_max) noexcept {
  const uint64_t d = a >= b ? (a - b) : (b - a);
  return r_min <= d && d <= r_max;
}

